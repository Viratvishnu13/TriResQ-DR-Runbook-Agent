"""Run the tests, every scenario and the retrieval set, then write docs/evidence/.

    python scripts/evaluate.py
"""
import json
import re
import subprocess
import sys
import tempfile
import time
import xml.etree.ElementTree as ET
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path[:0] = [str(ROOT / "src"), str(ROOT / "tests")]

from conftest import begin  # noqa: E402
from drill.coordinator import Coordinator  # noqa: E402
from test_drill import finish  # noqa: E402

DIMENSIONS = {"T01": "Normal use", "T02": "Invalid input", "T03": "Data protection", "T04": "Prompt injection",
              "T05": "Access control", "T06": "Hallucination", "T07": "Content safety", "T08": "Failure handling",
              "T09": "Cost and recursion", "T10": "Human approval"}


def run_tests():
    with tempfile.TemporaryDirectory() as tmp:
        report = Path(tmp) / "junit.xml"
        subprocess.run([sys.executable, "-m", "pytest", "-q", f"--junitxml={report}"], cwd=ROOT, check=False)
        cases = []
        for case in ET.parse(report).getroot().iter("testcase"):
            failed = any(child.tag in ("failure", "error") for child in case)
            skipped = any(child.tag == "skipped" for child in case)
            cases.append((case.get("name"), not failed and not skipped))
    guardrails = []
    for key, dimension in DIMENSIONS.items():
        mine = [ok for name, ok in cases if name.startswith(f"test_{key}_")]
        guardrails.append({"id": f"T-{key[1:]}", "dimension": dimension, "total": len(mine), "passed": sum(mine),
                           "result": "PASS" if mine and all(mine) else "FAIL"})
    return {"total": len(cases), "passed": sum(ok for _, ok in cases)}, guardrails


def run_scenarios(coord):
    results, report_ms = [], []
    for scenario in coord.operator.list_scenarios():
        drill_id = begin(coord, scenario["scenario_id"])
        finish(coord, drill_id)
        started = time.perf_counter()
        report = coord.report(drill_id)
        coord.report_markdown(drill_id)
        report_ms.append((time.perf_counter() - started) * 1000)
        results.append({"scenario_id": scenario["scenario_id"], "expected": scenario["expected_outcome"],
                        "actual": report["overall_result"],
                        "match": report["overall_result"] == scenario["expected_outcome"],
                        "unapproved_actions": len(report["integrity"]["actions_without_matching_approval"]),
                        "log_valid": report["integrity"]["event_chain_valid"]})
        if scenario["scenario_id"] in ("nominal_success", "dns_failure_rollback"):
            path = ROOT / "docs" / "evidence" / f"sample_report_{scenario['scenario_id']}.md"
            path.write_text(coord.report_markdown(drill_id), encoding="utf-8", newline="\n")
    return results, round(max(report_ms), 1)


def run_retrieval(coord):
    cases = []
    for item in json.loads((ROOT / "evals" / "retrieval_golden.json").read_text(encoding="utf-8")):
        hits = [h["citation"] for h in coord.knowledge.search(item["query"], application="FINANCE-PROD", limit=3)]
        rank = hits.index(item["expected"]) + 1 if item["expected"] in hits else None
        cases.append({**item, "top": hits[0] if hits else None, "rank": rank})
    known = [c for c in cases if c["expected"]]
    unknown = [c for c in cases if not c["expected"]]
    return {"answerable": len(known), "out_of_scope": len(unknown),
            "hit_at_1": sum(c["rank"] == 1 for c in known) / len(known),
            "hit_at_3": sum(c["rank"] is not None for c in known) / len(known),
            "mrr": round(sum(1 / c["rank"] for c in known if c["rank"]) / len(known), 3),
            "refusal_accuracy": sum(c["top"] is None for c in unknown) / len(unknown), "cases": cases}


def write_safety_record(evidence, guardrails, when):
    """The ten safety tests in the participant guide's format. 'Observed' is shown only if its tests passed."""
    cases = json.loads((ROOT / "evals" / "safety_cases.json").read_text(encoding="utf-8"))
    rows = ["# Safety and guardrail test record", "",
            f"Generated by `python scripts/evaluate.py` at {when} from the automated tests named `test_T01_*` to "
            "`test_T10_*`.", "", "| ID | Dimension | Scenario | Expected | Observed | Tests | Result | Limits of coverage |",
            "|---|---|---|---|---|---|---|---|"]
    for g in guardrails:
        scenario, expected, observed, limits = cases[g["id"]]
        seen = observed if g["result"] == "PASS" else "TESTS FAILED - see pytest output"
        rows.append(f"| {g['id']} | {g['dimension']} | {scenario} | {expected} | {seen} | "
                    f"{g['passed']}/{g['total']} | {g['result']} | {limits or '-'} |")
    (evidence / "SAFETY_TESTS.md").write_text("\n".join(rows) + "\n", encoding="utf-8", newline="\n")


def main():
    evidence = ROOT / "docs" / "evidence"
    evidence.mkdir(parents=True, exist_ok=True)
    tests, guardrails = run_tests()
    with tempfile.TemporaryDirectory() as tmp:
        coord = Coordinator(Path(tmp) / "eval.db", secret=b"evaluation-only")
        scenarios, report_ms = run_scenarios(coord)
        retrieval = run_retrieval(coord)
    result = {"generated_at": datetime.now(timezone.utc).isoformat(), "tests": tests, "guardrails": guardrails,
              "scenarios": scenarios, "retrieval": retrieval, "report_generation_ms": report_ms,
              "model_evaluated": False}
    (evidence / "evaluation.json").write_text(json.dumps(result, indent=2), encoding="utf-8", newline="\n")

    lines = ["# Evaluation evidence", "", f"Generated by `python scripts/evaluate.py` at {result['generated_at']}.",
             "Scenario runs use an automated coordinator that approves every request. Model answers are not "
             "evaluated here; at runtime each one passes a deterministic reference guard.", "",
             f"**Automated tests:** {tests['passed']}/{tests['total']} passed.", "", "## Guardrail matrix", "",
             "| ID | Dimension | Tests passed | Result |", "|---|---|---|---|"]
    lines += [f"| {g['id']} | {g['dimension']} | {g['passed']}/{g['total']} | {g['result']} |" for g in guardrails]
    lines += ["", "## Scenario matrix", "", "| Scenario | Expected | Actual | Unapproved actions | Log chain |",
              "|---|---|---|---|---|"]
    lines += [f"| {s['scenario_id']} | {s['expected']} | {s['actual']} | {s['unapproved_actions']} | "
              f"{'valid' if s['log_valid'] else 'BROKEN'} |" for s in scenarios]
    lines += ["", "## Retrieval (SQLite FTS5 / BM25)", "",
              f"Hit@1 {retrieval['hit_at_1']:.0%}, hit@3 {retrieval['hit_at_3']:.0%}, MRR {retrieval['mrr']}, "
              f"off-topic questions refused {retrieval['refusal_accuracy']:.0%}. The set is small "
              f"({len(retrieval['cases'])} questions) and was written by the team, so treat it as a regression "
              "check rather than a benchmark.", "", "| Question | Expected | Top result | Rank |", "|---|---|---|---|"]
    lines += [f"| {c['query']} | {c['expected'] or '(nothing)'} | {c['top'] or 'nothing'} | {c['rank'] or '-'} |"
              for c in retrieval["cases"]]
    lines += ["", f"Slowest report generation (JSON plus Markdown): {report_ms} ms on this machine.", ""]
    (evidence / "EVALUATION.md").write_text("\n".join(lines), encoding="utf-8", newline="\n")

    write_safety_record(evidence, guardrails, result["generated_at"])

    ok = tests["passed"] == tests["total"] and all(g["result"] == "PASS" for g in guardrails) \
        and all(s["match"] and not s["unapproved_actions"] for s in scenarios)
    print(f"tests {tests['passed']}/{tests['total']} | scenarios {sum(s['match'] for s in scenarios)}/{len(scenarios)}"
          f" | hit@1 {retrieval['hit_at_1']:.0%} hit@3 {retrieval['hit_at_3']:.0%} refusal "
          f"{retrieval['refusal_accuracy']:.0%} | report {report_ms} ms")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
